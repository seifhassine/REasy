def dump_types(dump: Path) -> list[dict]:
    return [item for item in json.loads(dump.read_text(encoding="utf-8")).values() if isinstance(item, dict)]


def field_names(types: list[dict]) -> set[str]:
    return {str(field.get("name", "")).casefold() for item in types for field in item.get("fields", ())}


def spelling(field: str, held: set[str]) -> str | None:
    return next((name for name in (field, *SPELLINGS.get(field, ())) if name.casefold() in held), None)


def game_fields(game: str, types: list[dict]) -> dict[str, str | None]:
    held = field_names(types)
    labels = {item.get("name"): [field.get("name") for field in item["fields"]] for item in types if item.get("fields")}
    names = {meaning: spelling(field, held) for meaning, field in FIELDS.items()}
    for meaning, (owner, index) in CONFIRMED.get(game.upper(), {}).items():
        names[meaning] = labels[owner][index]
    return names


def main() -> None:
    notes = [
        "By game (upper case), the engine fields the scene graph reads, by meaning: the game's dump label of a field",
        "its executable confirms, else RE4's names (or the game's own spelling of one) where the game's RSZ dump has a",
        "field of that name in any case (the graph ignores case), null where none of its types has one (the read takes",
        "its default). Generated by tools/scene_fields_catalog.py; docs/internals/scene-fields.md."]
    table = {}
    for game, name in sorted(DEFAULT_RSZ_JSONS.items(), key=lambda item: item[0].upper()):
        table[game.upper()] = game_fields(game, dump_types(DUMPS / name))
    OUTPUT.write_text(json.dumps(table, indent=1) + "\n", encoding="utf-8", newline="\n")
    OUTPUT.with_name(f"{OUTPUT.stem}_comments.json").write_text(
        json.dumps({"": notes}, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(table)} games -> {OUTPUT}")


if __name__ == "__main__":
    main()
